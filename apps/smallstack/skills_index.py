def _project_root_for(root: Path) -> Path | None:
    """The project root that owns ``docs/skills`` — ``BASE_DIR`` in a real
    project; for an arbitrary ``root`` (tests), its grandparent when it looks
    like ``<project>/docs/skills``, else None (no skills tree to manage)."""
    if root == Path(settings.BASE_DIR) / "docs" / "skills":
        return Path(settings.BASE_DIR)
    if root.name == "skills" and root.parent.name == "docs":
        return root.parent.parent
    return None


_NAME_BAD = re.compile(r"[^a-z0-9]+")
_MD_LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")


def skill_name(file: str) -> str:
    """A spec-valid skill name from a skill file path: lowercase, ``a-z0-9-``,
    no leading/trailing/double hyphens, ≤64 chars. ``mcp/verify-mcp.md`` →
    ``mcp-verify-mcp``; ``merge-0.12.0.md`` → ``merge-0-12-0``."""
    raw = file.removesuffix(".md").replace("/", "-").lower()
    name = _NAME_BAD.sub("-", raw).strip("-")
    while "--" in name:
        name = name.replace("--", "-")
    return name[:64].rstrip("-")


def plain_description(description: str) -> str:
    """The README description as plain text for the ``description`` field:
    links keep their text, emphasis and code marks go, whitespace collapses,
    and the result fits the spec's 1024-character cap."""
    text = _MD_LINK.sub(r"\1", description)
    text = text.replace("**", "").replace("`", "").replace("*", "")
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) > 1024:
        text = text[:1021].rsplit(" ", 1)[0] + "…"
    return text or "SmallStack skill."


def _yaml_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _intro(content: str) -> str:
    """Everything before the second H2 — the skill's opening, which is what a
    long skill's SKILL.md carries before pointing at the full reference."""
    lines = content.splitlines()
    seen = 0
    for i, line in enumerate(lines):
        if line.startswith("## "):
            seen += 1
            if seen == 2:
                return "\n".join(lines[:i]).rstrip()
    return content.rstrip()


def build_agent_skills(root: Path) -> dict[str, dict[str, str]]:
    """``{skill name: {relative path: content}}`` for every registered skill.

    A skill ≤ :data:`MAX_INLINE_LINES` long is inlined into ``SKILL.md``; a
    longer one keeps its full text under ``references/`` with the opening in
    ``SKILL.md`` (the spec's progressive-disclosure guidance).
    """
    skills: dict[str, dict[str, str]] = {}
    for row in parse_readme(root):
        source = root / row.file
        if not source.exists():
            continue
        content = source.read_text(encoding="utf-8")
        name = skill_name(row.file)
        meta = [
            f"  source: {_yaml_str('docs/skills/' + row.file)}",
            f"  section: {_yaml_str(row.section or 'Skills')}",
            f"  generated-by: {_yaml_str(GENERATED_BY)}",
        ]
        if row.scope:
            meta.append(f"  scope: {_yaml_str(row.scope)}")
        if row.local:
            meta.append(f"  origin: {_yaml_str('fork-local')}")
        head = (
            "---\n"
            f"name: {name}\n"
            f"description: {_yaml_str(plain_description(row.description))}\n"
            "license: MIT\n"
            "metadata:\n" + "\n".join(meta) + "\n"
            "---\n\n"
            f"> Generated from `docs/skills/{row.file}` by `make skills-index` — edit the source, not this file.\n\n"
        )
        files: dict[str, str] = {}
        if len(content.splitlines()) <= MAX_INLINE_LINES:
            files[SKILL_FILE] = head + content.rstrip() + "\n"
        else:
            ref = "references/" + Path(row.file).name
            files[SKILL_FILE] = (
                head
                + _intro(content)
                + f"\n\nThis skill is long; the full text is in [{ref}]({ref}) — read it before acting.\n"
            )
            files[ref] = content
        skills[name] = files
    return skills


def _generated_dirs(base: Path) -> list[Path]:
    """Skill directories under ``base`` that this generator wrote (by marker)."""
    if not base.is_dir():
        return []
    out: list[Path] = []
    for child in sorted(base.iterdir()):
        skill = child / SKILL_FILE
        if child.is_dir() and not child.is_symlink() and skill.is_file():
            try:
                if GENERATED_BY in skill.read_text(encoding="utf-8"):
                    out.append(child)
            except OSError:
                continue
    return out


def write_agent_skills(root: Path, project_root: Path | None = None) -> list[Path]:
    """Write ``.agents/skills/<name>/`` for every registered skill, remove the
    generated directories that no longer correspond to one, and keep
    ``.claude/skills/<name>`` as a relative symlink to each. Directories the
    generator did not write (a hand-made skill) are left alone."""
    import shutil

    base = project_root if project_root is not None else _project_root_for(root)
    if base is None:
        return []
    agents_dir = base / AGENT_SKILLS_SUBDIR
    claude_dir = base / CLAUDE_SKILLS_SUBDIR
    expected = build_agent_skills(root)

    written: list[Path] = []
    agents_dir.mkdir(parents=True, exist_ok=True)
    for name, files in expected.items():
        target = agents_dir / name
        if target.is_dir():
            # Replace wholesale so a reference that moved inline doesn't linger.
            for stale in target.rglob("*"):
                if stale.is_file() and stale.relative_to(target).as_posix() not in files:
                    stale.unlink()
        for rel, content in files.items():
            path = target / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                path.write_text(content, encoding="utf-8")
            written.append(path)
    for stale_dir in _generated_dirs(agents_dir):
        if stale_dir.name not in expected:
            shutil.rmtree(stale_dir)

    claude_dir.mkdir(parents=True, exist_ok=True)
    for name in expected:
        link = claude_dir / name
        rel_target = Path("..") / ".." / AGENT_SKILLS_SUBDIR / name
        if link.is_symlink():
            if link.readlink() == rel_target:
                continue
            link.unlink()
        elif link.exists():
            continue  # a hand-made Claude skill with the same name wins
        link.symlink_to(rel_target, target_is_directory=True)
    for link in sorted(claude_dir.iterdir()) if claude_dir.is_dir() else []:
        if link.is_symlink() and AGENT_SKILLS_SUBDIR.as_posix() in link.readlink().as_posix():
            if link.name not in expected:
                link.unlink()
    return written


def agent_skills_stale(root: Path, project_root: Path) -> bool:
    """True when ``.agents/skills`` or the ``.claude/skills`` links differ
    from what the registries would generate."""
    agents_dir = project_root / AGENT_SKILLS_SUBDIR
    claude_dir = project_root / CLAUDE_SKILLS_SUBDIR
    expected = build_agent_skills(root)
    for name, files in expected.items():
        for rel, content in files.items():
            path = agents_dir / name / rel
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                return True
        link = claude_dir / name
        if not link.is_symlink() and not (link / SKILL_FILE).is_file():
            return True
    for gen in _generated_dirs(agents_dir):
        if gen.name not in expected:
            return True
    return False
